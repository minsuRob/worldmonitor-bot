"""Per-book rule tables generated from the strategy plugins, so the docs cannot drift from the code.

  python3 gen_rules_doc.py --write   # rewrite the table between the rules-table markers in each doc
  python3 gen_rules_doc.py --check   # exit 1 (with a diff) if a doc's table differs from the code

Docs: stockdesk/README.md (English) and docs/project/stockdesk/books.md (Korean; skipped if absent, e.g. on the box).
Every number comes from config.py and each strategy's PARAMS/OVERRIDES via Strategy.describe(); only the wording lives there.
출처 패턴: desk/manual/gen_rules_doc.py.
"""
import sys, os, difflib
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import config as C
import strategies

BEGIN, END = "<!-- rules-table:begin (generated by stockdesk/gen_rules_doc.py; edit the code, then --write) -->", "<!-- rules-table:end -->"
DOCS = {"en": os.path.join(HERE, "README.md"),
        "ko": os.path.join(os.path.dirname(HERE), "docs", "project", "stockdesk", "books.md")}
HEADERS = {"en": ["| Book | Market | Ledger | Screen | Size | Buy rule | Exits | Slots (screen → fill) |", "|---|---|---|---|---|---|---|---|"],
           "ko": ["| 장부 | 시장 | 스크린 | 크기 | 매수 규칙 | 매도 | 슬롯 (스크린 → 체결) |", "|---|---|---|---|---|---|---|"]}
COLUMNS = ("screen", "size", "buy", "exits")

def row(st, lang):
    d = st.describe(lang)
    slots = f"`{st.slots['screen']}` → `{st.slots['fill_entry']}`"
    label = f"{st.code} {st.name}"
    if lang == "en":
        return f"| {label} | {st.market} | state/books/{st.code}.db | {d['screen']} | {d['size']} | {d['buy']} | {d['exits']} | {slots} |"
    return f"| {label} | {st.market} | {d['screen']} | {d['size']} | {d['buy']} | {d['exits']} | {slots} |"

def table(lang):
    return "\n".join(HEADERS[lang] + [row(st, lang) for st in strategies.REGISTRY.values()])

def legend():
    parts = [f"{st.code}={st.name}" for st in strategies.REGISTRY.values()]
    return "books: " + "  ".join(parts) + f" | shared RISK identical in every book (max pos {C.MAX_POSITION_PCT * 100:g}%, daily loss {C.DAILY_LOSS_LIMIT_PCT * 100:g}%, DD halt {C.MAX_DRAWDOWN_HALT_PCT * 100:g}%)"

def render(text, lang):
    if BEGIN not in text or END not in text: raise ValueError("rules-table markers not found")
    head, rest = text.split(BEGIN, 1); _, tail = rest.split(END, 1)
    return head + BEGIN + "\n" + table(lang) + "\n" + END + tail

def check():
    bad = []
    for lang, path in DOCS.items():
        if not os.path.exists(path): continue
        cur = open(path, encoding="utf-8").read(); new = render(cur, lang)
        if cur != new:
            bad.append((lang, path, "".join(difflib.unified_diff(cur.splitlines(True), new.splitlines(True), path, "generated"))))
    return bad

if __name__ == "__main__":
    mode = (sys.argv[1:] or ["--check"])[0]
    for lang, path in DOCS.items():
        if not os.path.exists(path): print(f"skip {path} (not present)")
    if mode == "--write":
        for lang, path in DOCS.items():
            if not os.path.exists(path): continue
            cur = open(path, encoding="utf-8").read(); new = render(cur, lang)
            if cur != new: open(path, "w", encoding="utf-8").write(new); print(f"updated {path}")
            else: print(f"unchanged {path}")
    elif mode == "--check":
        bad = check()
        for _, path, diff in bad: print(diff)
        print("rules tables OK" if not bad else f"rules tables differ from code in {len(bad)} doc(s); run --write")
        sys.exit(1 if bad else 0)
    else: sys.exit(__doc__)
