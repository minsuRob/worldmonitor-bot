HEADERS = {"en": ["| Book | Ledger | VET (difference from BASE) | Size | Buy rule | Exits |", "|---|---|---|---|---|---|"],
           "ko": ["| 장부 | VET (BASE와 다른 점) | 크기 | 매수 규칙 | 매도 |", "|---|---|---|---|---|"]}
BOOKS = ("BASE", "A", "B", "C", "D")

def table(lang):
    row = {"en": row_en, "ko": row_ko}[lang]
    return "\n".join(HEADERS[lang] + [row(v) for v in BOOKS])

def legend():
    """One-line book legend for variant_report.py."""
    return (f"A=EV rule (p*b-(1-p)-{BR.ROUNDTRIP_COST * 100:g}%>0)  B=top holder {pct(val('B', 'VET_TOP_HOLDER_MAX'))}% (old C)  "
            "C=aggressive momentum rider  D=aggressive early sniper (Claude veto)  | shared RISK identical; C/D add own exits")

def render(text, lang):
    """Return text with the marked block replaced by the generated table; ValueError if the markers are missing."""
    if BEGIN not in text or END not in text: raise ValueError("rules-table markers not found")
    head, rest = text.split(BEGIN, 1); _, tail = rest.split(END, 1)
    return head + BEGIN + "\n" + table(lang) + "\n" + END + tail

def check():
    """[(lang, path, diff)] for every present doc whose table differs from the code."""
    bad = []
    for lang, path in DOCS.items():
        if not os.path.exists(path): continue
        cur = open(path, encoding="utf-8").read(); new = render(cur, lang)
        if cur != new:
            bad.append((lang, path, "".join(difflib.unified_diff(cur.splitlines(True), new.splitlines(True), path, "generated"))))
    return bad

if __name__ == "__main__":
    mode = (sys.argv[1:] or ["--check"])[0]
    for lang, path in DOCS.items():
        if not os.path.exists(path): print(f"skip {path} (not present)")
    if mode == "--write":
        for lang, path in DOCS.items():
            if not os.path.exists(path): continue
            cur = open(path, encoding="utf-8").read(); new = render(cur, lang)
            if cur != new: open(path, "w", encoding="utf-8").write(new); print(f"updated {path}")
            else: print(f"unchanged {path}")
    elif mode == "--check":
        bad = check()
        for _, path, diff in bad: print(diff)
        print("rules tables OK" if not bad else f"rules tables differ from code in {len(bad)} doc(s); run --write")
        sys.exit(1 if bad else 0)
    else: sys.exit(__doc__)
