    if v == "D":
        r30 = p["run30"]
        vet = (f"{top}; age {pre['age_min_min']:g}m..{pre['age_max_h']:g}h; liq >={usd_k(val(v, 'VET_MIN_LIQ'))}; >={p['post']['holders_min']} holders; "
               f"m5 buys/sells >={pre['m5_buy_sell_ratio']:g} with >={pre['m5_buys_min']} buys; 5m vol pace >={pre['vol_accel_min']:g}x 1h pace; "
               f"m5 > {pre['m5_min']:g}%; h1 <{val(v, 'VET_H1_ALREADY_PRICED'):g}%; quote token {'/'.join(pre['quote_allow'].values())} only (`D_quote_not_sol`); "
               f"no chasing: skip if it ran >={r30['max_mult']:g}x within {r30['window_min']:g} min on GeckoTerminal 1m candles "
               f"(`D_run30_ge_{r30['max_mult']:g}x`, fetch fail / no candle = `D_run30_unknown`, fail closed)")
        size = (f"fixed {pct(frac)}% (~${C.START_BALANCE * frac:,.0f}; min order ${C.MIN_ORDER:g}), max {mo} open, "
                f"{pct(val(v, 'SLIPPAGE_BUDGET'))}% slippage budget")
        return f"| D early sniper | variants/D.db | {vet} | {size} | {buy} | {exits} |"
    raise KeyError(v)

