"""Per-book rule tables generated from the code, so the docs cannot drift from config.py / book_rules.py.

  python3 manual/gen_rules_doc.py --write   # rewrite the table between the rules-table markers in each doc
  python3 manual/gen_rules_doc.py --check   # exit 1 (with a diff) if a doc's table differs from the code

Docs: desk/README.md (English) and docs/project/paper-books.md (Korean; repo only, skipped if the file is absent, e.g. on the box).
Every number comes from config.py (BASE) and book_rules.OVERRIDES / PARAMS; only the wording lives here.
"""
import sys, os, difflib
HERE = os.path.dirname(os.path.abspath(__file__)); DESK = os.path.dirname(HERE)
sys.path.insert(0, DESK); sys.path.insert(0, HERE)
import config as C
import book_rules as BR

BEGIN, END = "<!-- rules-table:begin (generated by desk/manual/gen_rules_doc.py; edit the code, then --write) -->", "<!-- rules-table:end -->"
DOCS = {"en": os.path.join(DESK, "README.md"),
        "ko": os.path.join(os.path.dirname(DESK), "docs", "project", "paper-books.md")}

def val(v, k): return BR.OVERRIDES[v].get(k, getattr(C, k))
def pct(x): return f"{x * 100:g}"
def usd_k(x): return f"${x / 1000:g}k"

def kelly_raw():
    p, b = C.MEME_ASSUMED_P_WIN, C.MEME_ASSUMED_PAYOFF_B
    return p - (1 - p) / b

def vet_diff(v):
    """Numbers a book changes vs BASE: (top holder, h1 limit, min liquidity) or None when equal to BASE."""
    keys = ("VET_TOP_HOLDER_MAX", "VET_H1_ALREADY_PRICED", "VET_MIN_LIQ")
    return {k: val(v, k) for k in keys if val(v, k) != getattr(C, k)}

